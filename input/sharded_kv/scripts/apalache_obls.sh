#!/usr/bin/env bash
# Apalache BMC of local Inv / Obl guarantees (after TLC campaign).
#
# Usage (from repo root):
#   JULAYC_OPTS='--opt-tla=apalache' ./input/sharded_kv/scripts/compile.sh
#   ./input/sharded_kv/scripts/apalache_obls.sh           # all Obls
#   ./input/sharded_kv/scripts/apalache_obls.sh StoreObl  # one
#
# Requires: apalache-mc on PATH or APALACHE_MC set (default ~/apalache/bin/apalache-mc).

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
SKV_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
REPO_ROOT="$(cd "$SKV_DIR/../.." && pwd)"

APALACHE_MC="${APALACHE_MC:-$HOME/apalache/bin/apalache-mc}"
if [[ ! -x "$APALACHE_MC" ]]; then
  echo "error: apalache-mc not found (set APALACHE_MC)" >&2
  exit 1
fi

# Shallow BMC by default (plan: escalate only if needed). Store with lists is heavy.
LENGTH="${APALACHE_LENGTH:-3}"
OUT_DIR="${APALACHE_OUT:-$SKV_DIR/apalache-out}"
mkdir -p "$OUT_DIR"

pin_key_ab() {
  local cfg="$1"
  if [[ -f "$cfg" ]]; then
    sed -i.bak 's/CONSTANT Key = {"a", "b", "c", "d", "e"}/CONSTANT Key = {"a", "b"}/' "$cfg"
    rm -f "${cfg}.bak"
  fi
}

# Drop TypeOK from Apalache cfg: BoundedSeq×TypeOKInt explodes; Inv is the target.
strip_typeok_apa() {
  local cfg="$1"
  if [[ -f "$cfg" ]]; then
    sed -i.bak '/^INVARIANT TypeOK$/d' "$cfg"
    rm -f "${cfg}.bak"
  fi
}

pin_key_ab "$SKV_DIR/StoreObl.apalache.cfg"
pin_key_ab "$SKV_DIR/InboundEnvObl.apalache.cfg"
for c in StoreObl PutEnvObl InboundEnvObl ShardEnvObl; do
  strip_typeok_apa "$SKV_DIR/${c}.apalache.cfg"
done

# Inv operator name per Obl (listed guarantee / Safe).
inv_for() {
  case "$1" in
    StoreObl) echo StoreInv ;;
    PutEnvObl) echo PutInv ;;
    InboundEnvObl) echo InboundInv ;;
    ShardEnvObl) echo StoreAsm ;;
    *) echo "" ;;
  esac
}

# Minimal TLC cfg: CONSTANTS only (no TypeOK / expanded &-inv list). Inv via --inv.
make_inv_cfg() {
  local src="$1"
  local dst="$2"
  {
    echo '\* Apalache Inv-only (generated by apalache_obls.sh)'
    echo 'INIT Init'
    echo 'NEXT Next'
    echo 'CHECK_DEADLOCK FALSE'
    grep '^CONSTANT ' "$src" || true
  } > "$dst"
}

run_one() {
  local name="$1"
  local tla="$SKV_DIR/${name}.tla"
  local cfg="$SKV_DIR/${name}.apalache.cfg"
  local inv
  inv="$(inv_for "$name")"
  if [[ -z "$inv" ]]; then
    echo "error: unknown Obl $name" >&2
    return 1
  fi
  if [[ ! -f "$tla" || ! -f "$cfg" ]]; then
    echo "error: missing $tla or $cfg (compile with JULAYC_OPTS=--opt-tla=apalache)" >&2
    return 1
  fi
  local inv_cfg="$OUT_DIR/${name}.inv.cfg"
  make_inv_cfg "$cfg" "$inv_cfg"
  local log="$OUT_DIR/${name}.log"
  echo "==== Apalache $name inv=$inv length=$LENGTH ===="
  set +e
  (
    cd "$SKV_DIR"
    "$APALACHE_MC" check \
      --config="$inv_cfg" \
      --init=Init \
      --next=Next \
      --inv="$inv" \
      --length="$LENGTH" \
      --no-deadlock \
      --out-dir="$OUT_DIR/_apalache-out" \
      "${name}.tla"
  ) 2>&1 | tee "$log"
  local rc=${PIPESTATUS[0]}
  set -e
  if grep -qiE 'Checker reports no error|The outcome is: NoError|NoError' "$log"; then
    echo "PASS $name: Apalache NoError"
    return 0
  fi
  if grep -qiE 'The outcome is: Error|Checker has found|Counterexample' "$log"; then
    echo "FAIL $name: Apalache Error (see $log)" >&2
    return 1
  fi
  if [[ $rc -ne 0 ]]; then
    echo "FAIL $name: apalache-mc exit $rc (see $log)" >&2
    return 1
  fi
  echo "PASS $name: apalache-mc exit 0"
  return 0
}

DEFAULT_ORDER=(StoreObl PutEnvObl InboundEnvObl ShardEnvObl)

if [[ $# -gt 0 ]]; then
  for name in "$@"; do
    run_one "$name" || exit 1
  done
else
  for name in "${DEFAULT_ORDER[@]}"; do
    run_one "$name" || exit 1
  done
fi

echo "All Apalache Obl runs finished OK."
